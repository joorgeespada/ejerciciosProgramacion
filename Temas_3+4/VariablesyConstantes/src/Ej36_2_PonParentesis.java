public class Ej36_2_PonParentesis {
    public static void main (String []args){
        System.out.println(2 + 3 * 4 - 1);

        System.out.println((2 + 3) * (4 - 1)); //15

        System.out.println(2 + (3 * (4 - 1)));//11

        System.out.println(((2 + 3) * 4) - 1);//19

    }
}
